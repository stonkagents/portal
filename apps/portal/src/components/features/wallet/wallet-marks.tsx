/** Keyed by the KnownWallet slug. */
export const WALLET_MARKS: Readonly<Record<string, ComponentType<MarkProps>>> = {
  phantom: Phantom,
  solflare: Solflare,
  backpack: Backpack,
  metamask: MetaMask,
};

/** The slug of the known wallet a connector id or name refers to, if any. */
export function walletMarkSlug(...labels: readonly string[]): string | null {
  const lower = labels.map(l => l.toLowerCase());
  return Object.keys(WALLET_MARKS).find(slug => lower.some(l => l.includes(slug))) ?? null;
}
